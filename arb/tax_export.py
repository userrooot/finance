"""Year-end export of fills and closed trades as CSV for an Indian CA (Schedule VDA). Amounts are USDT."""
from __future__ import annotations

import csv
import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

IST = timezone(timedelta(hours=5, minutes=30))

FILL_COLS = ["date_ist", "exchange", "symbol", "market", "side", "qty", "price_usdt", "notional_usdt",
             "fee_usdt", "group_id", "maker"]
TRADE_COLS = ["open_date_ist", "close_date_ist", "group_id", "pnl_usdt", "fees_usdt", "funding_usdt",
              "taxable_gain_usdt", "loss_not_set_off_usdt"]

README = """Tax export notes (generated by `python -m arb tax-export`)

- All amounts are in USDT. Convert to INR at the rate your CA specifies (e.g. the rate on the transaction date).
- Dates are in IST (UTC+05:30). The year filter uses the IST calendar year.
- Under Sec 115BBH, losses from virtual digital assets cannot be set off against other income or gains,
  or carried forward. `loss_not_set_off_usdt` lists those losses; `taxable_gain_usdt` is max(pnl, 0) per trade.
- 1% TDS (Sec 194S) may apply on trades on Indian exchanges.
- pnl_usdt is the trade's realised cash flow including fees and funding as tracked by the bot; fees_usdt and
  funding_usdt are shown separately for reference.
- This is a bookkeeping aid, not tax advice. Verify everything with a CA.
"""


def _ist(ms: int) -> datetime:
    return datetime.fromtimestamp(ms / 1000, tz=timezone.utc).astimezone(IST)


def export_tax(state_dir, year: int, out_path) -> Path:
    state_dir, out = Path(state_dir), Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)

    fills = []
    fpath = state_dir / "fills.jsonl"
    if fpath.exists():
        for line in fpath.read_text().splitlines():
            if not line.strip():
                continue
            f = json.loads(line)
            t = _ist(int(f["ts_ms"]))
            if t.year == year:
                fills.append((int(f["ts_ms"]), [
                    t.strftime("%Y-%m-%d"), f["exchange"], f["symbol"], f["market"], f["side"], f["qty"], f["price"],
                    f["qty"] * f["price"], f["fee"], f["group_id"], bool(f.get("maker", False))]))
    fills.sort(key=lambda r: r[0])

    trades = []
    spath = state_dir / "state.json"
    if spath.exists():
        closed = json.loads(spath.read_text()).get("portfolio", {}).get("closed_trades", [])
        for tr in closed:
            c = _ist(int(tr["close_ms"]))
            if c.year != year:
                continue
            pnl = float(tr["pnl"])
            trades.append((int(tr["close_ms"]), [
                _ist(int(tr["open_ms"])).strftime("%Y-%m-%d"), c.strftime("%Y-%m-%d"), tr["group_id"], pnl,
                tr["fees"], tr["funding"], max(pnl, 0.0), min(pnl, 0.0)]))
    trades.sort(key=lambda r: r[0])

    for suffix, cols, rows in (("_fills.csv", FILL_COLS, fills), ("_trades.csv", TRADE_COLS, trades)):
        with open(f"{out}{suffix}", "w", newline="") as fh:
            w = csv.writer(fh)
            w.writerow(cols)
            w.writerows(r for _, r in rows)
    Path(f"{out}_README.txt").write_text(README)
    return out
